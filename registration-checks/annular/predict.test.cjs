'use strict';

const assert = require('node:assert/strict');
const {execFileSync, spawnSync} = require('node:child_process');
const {createHash} = require('node:crypto');
const path = require('node:path');
const {test} = require('node:test');
const {fixedXYZ, measuredRows, readResidualTable} = require('./height-transfer.cjs');
const {predictAt} = require('./predict.cjs');
const mesh = require('./mesh-transfer/result.json');
const rows = measuredRows(readResidualTable());
const samples = ['PHerc1203', 'PHerc0846A'];
const cli = path.join(__dirname, 'predict.cjs');

test('all 41 held-out vectors match the historical validator at nine decimal places', () => {
  // Generated by leaveOneHeightOut at af61e5354c1d71fc2d36cabf5b0446ac3c6a325f.
  const expected = '558e56a4b4f89994d4a6543d7fb884ebafc0248752bf52416704aea058b67ed0';
  const lines = [];
  for (const sample of samples) {
    const sites = rows.filter(row => row.sample === sample);
    for (const height of ['A', 'B', 'C']) {
      const training = sites.filter(row => !row.site.startsWith(height));
      for (const site of sites.filter(row => row.site.startsWith(height))) {
        const result = predictAt(sample, fixedXYZ(site), training);
        const decimals = result.correction_xyz_fixed_vox.map(value => value.toFixed(9));
        lines.push([sample, site.site, ...decimals].join('\t'));
      }
    }
  }
  assert.equal(lines.length, 41);
  assert.equal(createHash('sha256').update(lines.join('\n')).digest('hex'), expected);
});

test('six public mesh vertices reproduce the independent Python fits and frame sign', () => {
  assert.equal(mesh.results.length, 6);
  for (const vertex of mesh.results) {
    const training = rows.filter(row => !row.site.startsWith(vertex.height));
    const result = predictAt('PHerc1203', vertex.p, training);
    assert.equal(result.calibration.sites, vertex.train);
    for (let axis = 0; axis < 3; axis++) {
      assert.ok(Math.abs(result.correction_xyz_fixed_vox[axis] - vertex.d[axis]) < 1e-10);
    }
    const normal = result.correction_xyz_fixed_vox.reduce((sum, value, i) => sum + value * vertex.n[i], 0);
    assert.ok(Math.abs(normal - vertex.normal_vox) < 1e-10);
  }
});

test('the two all-site fits agree with an independent Cholesky solve at A11', () => {
  const checks = [
    ['PHerc1203', [4177, 4089, 9089], [-0.22408378525222955, 0.41380573059314907, 0.08130501861894943]],
    ['PHerc0846A', [4905, 4258, 3011], [-0.2553119587116753, 0.3493659694200419, -0.43843499370800537]],
  ];
  for (const [sample, point, independent] of checks) {
    const report = predictAt(sample, point, rows);
    assert.equal(report.calibration.nearest_site, 'A11');
    independent.forEach((value, i) => assert.ok(Math.abs(report.correction_xyz_fixed_vox[i] - value) < 1e-12));
  }
});

test('full fits report the nearest measured site and the 3D hull of each sample', () => {
  for (const sample of samples) {
    const sites = rows.filter(row => row.sample === sample);
    assert.equal(sites.length, sample === 'PHerc1203' ? 17 : 24);
    for (const site of sites) {
      const result = predictAt(sample, fixedXYZ(site), rows);
      assert.equal(result.calibration.sites, sites.length);
      assert.equal(result.calibration.hull, 'inside_or_on');
      assert.equal(result.calibration.nearest_site, site.site);
      assert.equal(result.calibration.nearest_distance_mm, 0);
    }
    const mean = [0, 1, 2].map(axis =>
      sites.reduce((sum, site) => sum + fixedXYZ(site)[axis], 0) / sites.length);
    assert.equal(predictAt(sample, mean, rows).calibration.hull, 'inside_or_on');
  }
  // This point fits in the axis-aligned bounding box of the measured 1203 sites.
  assert.equal(predictAt('PHerc1203', [1605, 4996, 9089], rows).calibration.hull, 'outside');
});

test('CLI reports a full-data public mesh example and rejects invalid input', () => {
  const point = mesh.results[0].p;
  const json = JSON.parse(execFileSync(process.execPath, [cli, 'PHerc1203', ...point.map(String)], {encoding:'utf8'}));
  assert.equal(json.calibration.sites, 17);
  assert.equal(json.calibration.hull, 'outside');
  assert.equal(json.calibration.nearest_site, 'A12');
  assert.ok(Math.abs(json.calibration.nearest_distance_mm - 4.987331282474115) < 1e-9);
  assert.deepEqual(json.fixed_xyz_vox, point);
  assert.deepEqual(json.correction_xyz_um, json.correction_xyz_fixed_vox.map(v => v * 9.362));
  const example = [-0.39575217694668924, 0.03757688620038846, -0.13007401939050944];
  example.forEach((value, i) => assert.ok(Math.abs(json.correction_xyz_fixed_vox[i] - value) < 1e-12));
  for (const args of [['unknown', 1, 2, 3], ['PHerc1203', 1, 2], ['PHerc0846A', 'NaN', 0, 0],
    ['PHerc0846A', '1e400', 0, 0], ['PHerc1203', -1, 0, 0]]) {
    const result = spawnSync(process.execPath, [cli, ...args.map(String)], {encoding:'utf8'});
    assert.equal(result.status, 2);
    assert.equal(result.stdout, '');
    assert.match(result.stderr, /Usage:/);
  }
});
