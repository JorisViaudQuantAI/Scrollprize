"""Independent small native-admission regressions; no model, network, or CT.

Expected masks for the fixtures are drawn analytically for 288- and 310-pixel
canvases. They are not generated by the validator's mask implementation.
"""
from __future__ import annotations

import copy
from contextlib import redirect_stdout
import hashlib
import io
import json
from pathlib import Path
import tempfile
import unittest

import numpy as np

from native_evidence import assess_pair, main, validate_native


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


class NativeEvidenceTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)

    def write_role(self, manifest, role, array):
        path = self.root / (manifest["name"] + "_" + role + ".npy")
        np.save(path, array, allow_pickle=array.dtype.hasobject)
        manifest["arrays"][role] = {
            "path": path.name, "sha256": sha(path), "dtype": str(array.dtype),
            "shape": list(array.shape), "axes": "LYX" if array.ndim == 3 else "YX",
        }

    def read_role(self, manifest, role):
        return np.load(self.root / manifest["arrays"][role]["path"], allow_pickle=False)

    def make(self, name="a", hann=False, size=288):
        self.assertIn(size, (288, 310))
        self.assertTrue(hann or size == 288)
        frame = {
            "scroll": "PHerc0125", "source_volume": "synthetic-volume",
            "chart_id": "synthetic-prepared-chart", "origin_yx": [0, 0],
            "registration_status": "synthetic_known_frame",
        }
        recipe = {
            "model_sha256": "1" * 64, "pipeline_sha256": "2" * 64,
            "runner_sha256": "3" * 64, "model_code_sha256": "4" * 64,
            "normalization": "uint8 -> FP32 clip[0,200]/255 exactly once",
            "precision": "fp32", "stride": 48 if hann else 96,
            "blend": "hann" if hann else "none", "input_window": 128,
            "output_window": 96, "halo": 16,
            "tiling_policy": "studio_v1_end_anchored",
            "source_domain": "synthetic", "origin_yx": [0, 0],
            "phase_yx": [0, 0], "direction": "asc",
        }
        manifest = {
            "schema": "funnel.native_evidence.v1", "name": name,
            "frame": frame, "recipe": recipe, "depth_samples": list(range(8, 24)),
            "depth_units": "source_plane_index", "signed_offsets_um": None,
            "depth_unknown_reason": None, "arrays": {},
            "cost": {"map_elapsed_seconds": 0.125, "cpu_ms": None, "gpu_ms": 0,
                     "io_bytes": None, "model_windows": (64 if size == 310 else 36) if hann else 9,
                     "sentinel_forwards": 1},
            "calibration": {"identity_sentinel_pass": True,
                            "semantic_control_status": "NOT_MATCHED", "training_exposure": "unknown"},
            "scientific_status": "unconfirmed", "support_basis": "EXPLICIT_PREPARED_MASK",
        }
        stack = np.broadcast_to(np.arange(1, 17, dtype=np.uint8)[:, None, None], (16, size, size)).copy()
        context = np.zeros((size, size), bool)
        # 288: only the central 96-square is free of every unsafe contributor.
        # 310 Hann: extra end anchor is 214, so strict context ends there.
        end = 214 if size == 310 else 192
        context[96:end, 96:end] = True
        arrays = {
            "input": stack, "source_depth": np.ones_like(stack, bool),
            "probability": np.full((size, size), 0.25, np.float32),
            "output_valid": np.ones((size, size), bool),
            "source_valid": np.ones((size, size), bool), "context_valid": context,
        }
        for role, array in arrays.items():
            self.write_role(manifest, role, array)
        return manifest

    def reverse(self, manifest, name="b"):
        other = copy.deepcopy(manifest)
        other["name"] = name
        other["depth_samples"] = other["depth_samples"][::-1]
        other["recipe"]["direction"] = "desc"
        for role in manifest["arrays"]:
            array = self.read_role(manifest, role)
            self.write_role(other, role, array[::-1] if role in ("input", "source_depth") else array)
        return other

    def assert_invalid(self, manifest, code):
        result = validate_native(manifest, self.root)
        self.assertFalse(result["valid"], result)
        self.assertIn(code, [e["code"] for e in result["errors"]], result)
        self.assertFalse(result["production_complete"])
        return result

    def test_known_native_fixture_is_read_only_and_not_production(self):
        manifest = self.make()
        before = {p.name: (sha(p), p.stat().st_mtime_ns) for p in self.root.iterdir()}
        result = validate_native(manifest, self.root)
        self.assertTrue(result["valid"], result)
        self.assertEqual(result["derived"]["context_valid_pixels"], 96 * 96)
        self.assertIsNone(result["derived"]["reported_cost"]["cpu_ms"])
        self.assertIsNone(result["derived"]["reported_cost"]["io_bytes"])
        self.assertEqual(result["scientific_admission"], "NOT_ESTABLISHED")
        self.assertFalse(result["production_complete"])
        self.assertFalse(result["derived"]["native_acquisition_verified"])
        self.assertEqual(before, {p.name: (sha(p), p.stat().st_mtime_ns) for p in self.root.iterdir()})

    def test_payload_corruption_is_not_hidden_by_valid_masks(self):
        manifest = self.make()
        path = self.root / manifest["arrays"]["probability"]["path"]
        with path.open("ab") as stream:
            stream.write(b"corruption")
        self.assert_invalid(manifest, "HASH_MISMATCH")

    def test_uint8_display_map_is_not_native_probability(self):
        manifest = self.make()
        self.write_role(manifest, "probability", np.full((288, 288), 64, np.uint8))
        self.assert_invalid(manifest, "ARRAY_DTYPE")

    def test_mask_must_be_boolean_not_zero_one_image(self):
        manifest = self.make()
        self.write_role(manifest, "source_valid", np.ones((288, 288), np.uint8))
        self.assert_invalid(manifest, "ARRAY_DTYPE")

    def test_descriptor_shape_and_loaded_shape_must_agree(self):
        manifest = self.make()
        manifest["arrays"]["probability"]["shape"] = [287, 288]
        self.assert_invalid(manifest, "ARRAY_SHAPE")

    def test_consistently_declared_wrong_shape_still_breaks_alignment(self):
        manifest = self.make()
        self.write_role(manifest, "source_valid", np.ones((287, 288), bool))
        self.assert_invalid(manifest, "MASK_ALIGNMENT")

    def test_axes_cannot_be_silently_transposed(self):
        manifest = self.make()
        manifest["arrays"]["probability"]["axes"] = "XY"
        self.assert_invalid(manifest, "ARRAY_AXES")

    def test_supported_nan_is_rejected(self):
        manifest = self.make()
        array = self.read_role(manifest, "probability")
        array[120, 120] = np.nan
        self.write_role(manifest, "probability", array)
        self.assert_invalid(manifest, "NONFINITE_SCORE")

    def test_supported_infinity_is_rejected(self):
        manifest = self.make()
        array = self.read_role(manifest, "probability")
        array[120, 120] = np.inf
        self.write_role(manifest, "probability", array)
        self.assert_invalid(manifest, "NONFINITE_SCORE")

    def test_supported_probability_outside_unit_interval_is_rejected(self):
        manifest = self.make()
        array = self.read_role(manifest, "probability")
        array[120, 120] = 1.25
        self.write_role(manifest, "probability", array)
        self.assert_invalid(manifest, "PROBABILITY_RANGE")

    def test_supported_zero_is_valid_not_missing_acquisition(self):
        manifest = self.make()
        self.write_role(manifest, "probability", np.zeros((288, 288), np.float32))
        result = validate_native(manifest, self.root)
        self.assertTrue(result["valid"], result)
        self.assertEqual(result["derived"]["output_valid_pixels"], 288 * 288)

    def test_unsupported_nan_does_not_become_observed(self):
        manifest = self.make()
        stack = self.read_role(manifest, "input")
        stack[:, 120, 120] = 0
        self.write_role(manifest, "input", stack)
        for role in ("output_valid", "context_valid"):
            mask = self.read_role(manifest, role)
            mask[120, 120] = False
            self.write_role(manifest, role, mask)
        probability = self.read_role(manifest, "probability")
        probability[120, 120] = np.nan
        self.write_role(manifest, "probability", probability)
        result = validate_native(manifest, self.root)
        self.assertTrue(result["valid"], result)
        self.assertEqual(result["derived"]["source_valid_pixels"], 288 * 288)
        self.assertEqual(result["derived"]["output_valid_pixels"], 288 * 288 - 1)

    def test_hash_correct_false_context_claim_is_rejected(self):
        manifest = self.make()
        context = self.read_role(manifest, "context_valid")
        context[0, 0] = True
        self.write_role(manifest, "context_valid", context)
        self.assert_invalid(manifest, "MASK_SEMANTICS")

    def test_source_mask_cannot_be_replaced_by_context_mask(self):
        manifest = self.make()
        self.write_role(manifest, "source_valid", self.read_role(manifest, "context_valid"))
        self.assert_invalid(manifest, "MASK_SEMANTICS")

    def test_single_depth_halo_hole_invalidates_full_contributing_window(self):
        manifest = self.make()
        source = self.read_role(manifest, "source_depth")
        source[7, 80, 80] = False  # In the central input's halo, outside its 96-square output.
        self.write_role(manifest, "source_depth", source)
        source_valid = self.read_role(manifest, "source_valid")
        source_valid[80, 80] = False
        self.write_role(manifest, "source_valid", source_valid)
        self.assert_invalid(manifest, "MASK_SEMANTICS")
        self.write_role(manifest, "context_valid", np.zeros((288, 288), bool))
        result = validate_native(manifest, self.root)
        self.assertTrue(result["valid"], result)
        self.assertIn("NO_ADMISSIBLE_CONTEXT", [x["code"] for x in result["warnings"]])

    def test_hann_context_is_intersection_of_all_contributors(self):
        manifest = self.make(hann=True)
        source = self.read_role(manifest, "source_depth")
        source[0, 40, 40] = False
        self.write_role(manifest, "source_depth", source)
        source_valid = self.read_role(manifest, "source_valid")
        source_valid[40, 40] = False
        self.write_role(manifest, "source_valid", source_valid)
        # The input at (96,96) is safe, but (48,48) contributes there and is not.
        self.assert_invalid(manifest, "MASK_SEMANTICS")
        context = self.read_role(manifest, "context_valid")
        context[96:144, 96:144] = False
        self.write_role(manifest, "context_valid", context)
        result = validate_native(manifest, self.root)
        self.assertTrue(result["valid"], result)
        self.assertEqual(result["derived"]["context_valid_pixels"], 96 * 96 - 48 * 48)

    def test_hann_end_anchor_and_partial_last_windows_are_counted(self):
        result = validate_native(self.make(hann=True, size=310), self.root)
        self.assertTrue(result["valid"], result)
        self.assertEqual(result["derived"]["model_windows"], 64)
        self.assertEqual(result["derived"]["context_valid_pixels"], 118 * 118)

    def test_skipped_all_zero_window_is_not_counted_as_a_forward(self):
        manifest = self.make()
        stack = self.read_role(manifest, "input")
        stack[:, :96, :96] = 0
        self.write_role(manifest, "input", stack)
        valid = self.read_role(manifest, "output_valid")
        valid[:96, :96] = False
        self.write_role(manifest, "output_valid", valid)
        self.assert_invalid(manifest, "WINDOW_COUNT")
        manifest["cost"]["model_windows"] = 8
        self.assertTrue(validate_native(manifest, self.root)["valid"])

    def test_crop_origin_cannot_change_without_phase_and_identity(self):
        manifest = self.make()
        manifest["frame"]["origin_yx"] = [0, 1]
        self.assert_invalid(manifest, "ORIGIN_MISMATCH")
        manifest["recipe"]["origin_yx"] = [0, 1]
        self.assert_invalid(manifest, "PHASE_MISMATCH")
        manifest["recipe"]["phase_yx"] = [0, 1]
        self.assertTrue(validate_native(manifest, self.root)["valid"])

    def test_unknown_depth_is_auditable_but_not_an_exact_pair(self):
        manifest = self.make()
        other = self.reverse(manifest)
        manifest["depth_samples"] = None
        manifest["depth_unknown_reason"] = "Prepared author sample has no source-plane mapping"
        result = validate_native(manifest, self.root)
        self.assertTrue(result["valid"], result)
        self.assertIn("UNKNOWN_DEPTHS", [x["code"] for x in result["warnings"]])
        pair = assess_pair(manifest, other, self.root)
        self.assertFalse(pair["valid"])
        self.assertEqual(pair["errors"][0]["code"], "PAIR_DEPTH_UNKNOWN")

    def test_exact_pair_is_same_observation_not_independent_replication(self):
        manifest = self.make()
        pair = assess_pair(manifest, self.reverse(manifest), self.root)
        self.assertTrue(pair["valid"], pair)
        self.assertFalse(pair["independent_replication"])
        self.assertFalse(pair["production_complete"])
        self.assertEqual(pair["scientific_admission"], "NOT_ESTABLISHED")

    def test_historical_one_plane_shift_is_not_exact_reversal(self):
        manifest = self.make()
        other = self.reverse(manifest)
        other["depth_samples"] = list(range(22, 6, -1))
        pair = assess_pair(manifest, other, self.root)
        self.assertFalse(pair["valid"])
        self.assertEqual(pair["errors"][0]["code"], "PAIR_DEPTH_SHIFT")

    def test_reversed_depth_labels_do_not_substitute_for_reversed_data(self):
        manifest = self.make()
        other = self.reverse(manifest)
        self.write_role(other, "input", self.read_role(manifest, "input"))
        pair = assess_pair(manifest, other, self.root)
        self.assertFalse(pair["valid"])
        self.assertEqual(pair["errors"][0]["code"], "PAIR_INPUT")

    def test_per_depth_source_must_reverse_even_if_aggregate_masks_match(self):
        manifest = self.make()
        source = self.read_role(manifest, "source_depth")
        source[0, 80, 80] = False
        self.write_role(manifest, "source_depth", source)
        source_valid = self.read_role(manifest, "source_valid")
        source_valid[80, 80] = False
        self.write_role(manifest, "source_valid", source_valid)
        self.write_role(manifest, "context_valid", np.zeros((288, 288), bool))
        other = self.reverse(manifest)
        self.write_role(other, "source_depth", source)  # Deliberately not reversed.
        pair = assess_pair(manifest, other, self.root)
        self.assertEqual(pair["members_valid"], [True, True], pair)
        self.assertFalse(pair["valid"])
        self.assertEqual(pair["errors"][0]["code"], "PAIR_SOURCE_SUPPORT")

    def test_pair_cannot_merge_different_crops(self):
        manifest = self.make()
        other = self.reverse(manifest)
        other["frame"]["origin_yx"] = [0, 96]
        other["recipe"]["origin_yx"] = [0, 96]
        pair = assess_pair(manifest, other, self.root)
        self.assertFalse(pair["valid"])
        self.assertEqual(pair["errors"][0]["code"], "PAIR_FRAME")

    def test_pair_cannot_merge_precision_recipes(self):
        manifest = self.make()
        other = self.reverse(manifest)
        other["recipe"]["precision"] = "fp16"
        pair = assess_pair(manifest, other, self.root)
        self.assertFalse(pair["valid"])
        self.assertEqual(pair["errors"][0]["code"], "PAIR_RECIPE")

    def make_implicit(self, manifest):
        receipt = self.root / (manifest["name"] + "_original_receipt.json")
        receipt.write_text(json.dumps({
            "source_support_sha256": None, "job": {"input": "prepared.npy"},
            "input_sha256": manifest["arrays"]["input"]["sha256"], "input_shape": [16, 288, 288],
        }))
        manifest["support_basis"] = "IMPLICIT_PREPARED_PRESENCE"
        manifest["arrays"]["source_depth"] = {
            "derivation": "all_true_as_executed", "evidence_path": receipt.name,
            "evidence_sha256": sha(receipt), "dtype": "bool", "shape": [16, 288, 288], "axes": "LYX",
        }

    def test_legacy_implicit_support_preserves_assumption_and_warning(self):
        manifest = self.make()
        self.make_implicit(manifest)
        result = validate_native(manifest, self.root)
        self.assertTrue(result["valid"], result)
        self.assertIn("ASSUMED_PREPARED_SUPPORT", [x["code"] for x in result["warnings"]])
        self.assertFalse(result["derived"]["native_acquisition_verified"])

    def test_implicit_support_needs_original_matching_receipt(self):
        manifest = self.make()
        self.make_implicit(manifest)
        row = manifest["arrays"]["source_depth"]
        receipt = self.root / row["evidence_path"]
        receipt.write_text(json.dumps({"source_support_sha256": "5" * 64, "job": {}}))
        row["evidence_sha256"] = sha(receipt)
        self.assert_invalid(manifest, "SUPPORT_DERIVATION")

    def test_implicit_support_receipt_must_belong_to_this_input(self):
        manifest = self.make()
        self.make_implicit(manifest)
        row = manifest["arrays"]["source_depth"]
        receipt = self.root / row["evidence_path"]
        evidence = json.loads(receipt.read_text())
        evidence["input_sha256"] = "9" * 64
        receipt.write_text(json.dumps(evidence))
        row["evidence_sha256"] = sha(receipt)
        self.assert_invalid(manifest, "SUPPORT_DERIVATION")

    def test_pair_cannot_mix_explicit_and_implicit_support_claims(self):
        manifest = self.make()
        other = self.reverse(manifest)
        self.make_implicit(other)
        pair = assess_pair(manifest, other, self.root)
        self.assertEqual(pair["members_valid"], [True, True], pair)
        self.assertFalse(pair["valid"])
        self.assertEqual(pair["errors"][0]["code"], "PAIR_SUPPORT_BASIS")

    def test_source_path_cannot_escape_bundle_even_with_correct_hash(self):
        manifest = self.make()
        manifest["arrays"]["probability"]["path"] = str(self.root / "a_probability.npy")
        self.assert_invalid(manifest, "ARRAY_PATH")

    def test_object_arrays_never_load_with_pickle(self):
        manifest = self.make()
        self.write_role(manifest, "probability", np.full((288, 288), "unsafe", dtype=object))
        self.assert_invalid(manifest, "ARRAY_LOAD")

    def test_calibration_attestation_does_not_create_production_completion(self):
        manifest = self.make()
        manifest["calibration"]["semantic_control_status"] = "PASS"
        manifest["scientific_status"] = "KNOWN_PUBLIC_CONTROL"
        result = validate_native(manifest, self.root)
        self.assertTrue(result["valid"], result)
        self.assertFalse(result["production_complete"])
        self.assertEqual(result["scientific_admission"], "NOT_ESTABLISHED")

    def test_discovery_status_is_not_admitted_by_array_validation(self):
        manifest = self.make()
        manifest["scientific_status"] = "CONFIRMED_NEW_LETTER"
        self.assert_invalid(manifest, "SCIENTIFIC_STATUS")

    def test_cli_json_and_exit_status_do_not_write_evidence(self):
        manifest = self.make()
        path = self.root / "manifest.json"
        path.write_text(json.dumps(manifest))
        output = io.StringIO()
        with redirect_stdout(output):
            code = main(["--manifest", str(path), "--root", str(self.root)])
        self.assertEqual(code, 0)
        self.assertTrue(json.loads(output.getvalue())["valid"])
        path.write_text("{malformed")
        output = io.StringIO()
        with redirect_stdout(output):
            code = main(["--manifest", str(path), "--root", str(self.root)])
        self.assertEqual(code, 1)
        self.assertEqual(json.loads(output.getvalue())["errors"][0]["code"], "MANIFEST_LOAD")


if __name__ == "__main__":
    unittest.main()
